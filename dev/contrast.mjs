// Calculates WCAG 2.x contrast ratios for every colour pair the theme actually uses.
// Token values are read from theme/assets/base.css, so the report always matches the code.
//   npm run contrast   →  prints the table and writes docs/contrast-report.md
import fs from 'node:fs';

const css = fs.readFileSync('theme/assets/base.css', 'utf8');
const rootBlock = css.slice(css.indexOf(':root {'), css.indexOf('}', css.indexOf(':root {')));
const tokens = Object.fromEntries([...rootBlock.matchAll(/--(color-[\w-]+):\s*(#[0-9A-Fa-f]{6})/g)].map((m) => [m[1], m[2].toUpperCase()]));

const lum = (hex) => {
  const [r, g, b] = [1, 3, 5].map((i) => parseInt(hex.slice(i, i + 2), 16) / 255).map((c) => (c <= 0.04045 ? c / 12.92 : ((c + 0.055) / 1.055) ** 2.4));
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
};
const ratio = (a, b) => { const [x, y] = [lum(a), lum(b)].sort((p, q) => q - p); return (x + 0.05) / (y + 0.05); };
const t = (name) => tokens[name] || name;

// [use, foreground token, background token, requirement: 4.5 text | 3 large/non-text]
const PAIRS = [
  ['Body text', 'color-text', 'color-background', 4.5],
  ['Body text on stone panels/cards', 'color-text', 'color-surface', 4.5],
  ['Text in inputs and drawers', 'color-text', 'color-surface-raised', 4.5],
  ['Secondary text', 'color-text-muted', 'color-background', 4.5],
  ['Secondary text on stone', 'color-text-muted', 'color-surface', 4.5],
  ['Secondary text on blossom tint (active detail)', 'color-text-muted', 'color-accent-soft', 4.5],
  ['Primary button text', 'color-action-text', 'color-action', 4.5],
  ['Primary button hover', 'color-action-text', 'color-action-hover', 4.5],
  ['Primary button pressed', 'color-action-text', 'color-action-pressed', 4.5],
  ['Selected states, "This piece" label (pine text)', 'color-action', 'color-background', 4.5],
  ['Hero heading last line (large text)', 'color-action', 'color-background', 3],
  ['Detail marker numbers (white on blossom)', 'color-on-accent', 'color-accent', 4.5],
  ['Blossom text: section numbers', 'color-accent', 'color-background', 4.5],
  ['Text on blossom tint (fit notes)', 'color-text', 'color-accent-soft', 4.5],
  ['Fit-note icon on blossom tint (non-text)', 'color-accent', 'color-accent-soft', 3],
  ['In-stock / success text', 'color-success', 'color-background', 4.5],
  ['Success message', 'color-success', 'color-success-bg', 4.5],
  ['Error text', 'color-error', 'color-background', 4.5],
  ['Error message / invalid field', 'color-error', 'color-error-bg', 4.5],
  ['Missing-content placeholder', 'color-warning', 'color-warning-bg', 4.5],
  ['Sold-out badge, town label', 'color-inverse-text', 'color-text', 4.5],
  ['Disabled button text (exempt, still checked)', 'color-text-muted', 'color-surface', 4.5],
  ['Focus ring vs page (non-text)', 'color-focus', 'color-background', 3],
  ['Focus ring vs stone (non-text)', 'color-focus', 'color-surface', 3],
  ['Control borders vs page (non-text)', 'color-border-strong', 'color-background', 3],
  ['Control borders vs input fill (non-text)', 'color-border-strong', 'color-surface-raised', 3],
  ['Selected swatch/chip ring vs page (non-text)', 'color-action', 'color-background', 3],
  ['Footer & announcement text', 'color-inverse-text', 'color-inverse', 4.5],
  ['Footer secondary text', 'color-inverse-muted', 'color-inverse', 4.5],
  ['Footer focus ring (non-text)', 'color-focus-inverse', 'color-inverse', 3],
  ['Footer input border (non-text)', 'color-inverse-border', 'color-inverse', 3],
  ['Footer button text', 'color-text', 'color-inverse-text', 4.5],
  ['Footer error text', 'color-error-bg', 'color-inverse', 4.5],
];

const rows = PAIRS.map(([use, fg, bg, need]) => {
  const r = ratio(t(fg), t(bg));
  return { use, fg: `${fg} ${t(fg)}`, bg: `${bg} ${t(bg)}`, ratio: r, need, pass: r >= need };
});

const lines = [
  '# Contrast report (generated)',
  '',
  `Generated by \`npm run contrast\` from the tokens in \`theme/assets/base.css\` on ${new Date().toISOString().slice(0, 10)}.`,
  'Ratios use the WCAG 2.x relative-luminance formula. Requirement: 4.5:1 for normal text, 3:1 for large text and required non-text indicators.',
  'Text over photographs is not covered here. See the design-system notes on overlays and solid label backings.',
  '',
  '| Use | Foreground | Background | Ratio | Needs | Result |',
  '| --- | --- | --- | --- | --- | --- |',
  ...rows.map((r) => `| ${r.use} | \`${r.fg}\` | \`${r.bg}\` | ${r.ratio.toFixed(2)}:1 | ${r.need}:1 | ${r.pass ? 'Pass' : '**Fail**'} |`),
  '',
  `${rows.filter((r) => r.pass).length} of ${rows.length} pairs pass.`,
];
fs.writeFileSync('docs/contrast-report.md', `${lines.join('\n')}\n`);
for (const r of rows) console.log(`${r.pass ? 'PASS' : 'FAIL'} ${r.ratio.toFixed(2).padStart(6)}:1 (≥${r.need})  ${r.use}`);
const failed = rows.filter((r) => !r.pass).length;
console.log(`\n${rows.length - failed}/${rows.length} pass`);
process.exitCode = failed ? 1 : 0;
