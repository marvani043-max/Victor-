// Builds the Shopify theme in ./shopify-theme and zips it for upload.
//   node scripts/build-shopify-theme.mjs
// Steps: photo-picker options -> bundled photos + snippet -> fonts/marks -> interactive.js
// (shared web components) -> theme.js -> theme.css (Tailwind over the Liquid) -> zip.
import fs from "node:fs";
import path from "node:path";
import { execFileSync } from "node:child_process";
import { buildSync, transformSync } from "esbuild";
import sharp from "sharp";

const ROOT = path.resolve(".");
const THEME = path.join(ROOT, "shopify-theme");
const ASSETS = path.join(THEME, "assets");
const SNIPPETS = path.join(THEME, "snippets");
const SRC = path.join(ROOT, "shopify-src");
const manifest = JSON.parse(fs.readFileSync(path.join(ROOT, "src/data/image-manifest.json"), "utf8"));
fs.mkdirSync(ASSETS, { recursive: true });

// 1. Bundled campaign photos (fallbacks for every image setting).
const PHOTOS = [
  ["trail-falls-front", "Trail: waterfall, black tee"],
  ["trail-falls-back", "Trail: waterfall, tee back"],
  ["trail-falls-wide", "Trail: waterfall, wide"],
  ["trail-falls-rock", "Trail: granite and falls"],
  ["trail-falls-duo", "Trail: two at the falls"],
  ["trail-overlook", "Trail: canyon overlook"],
  ["trail-ridge", "Trail: boulder"],
  ["trail-path", "Trail: forest path"],
  ["tunnel-crew", "Tunnel: the crew"],
  ["tunnel-pink-hoodie", "Tunnel: pink hoodie"],
  ["tunnel-crop-duo-2", "Tunnel: crop top duo"],
  ["tunnel-crop-sit", "Tunnel: sitting crew"],
  ["tunnel-crop-white", "Tunnel: white crop top"],
  ["tunnel-crop-white-2", "Tunnel: white crop top 2"],
  ["tunnel-zip-black", "Tunnel: black zip hoodie"],
  ["tunnel-zip-navy", "Tunnel: navy zip hoodie"],
  ["tunnel-tee-black-back", "Tunnel: tee back print"],
  ["night-boxy-trio", "Night: boxy tee trio"],
  ["detail-graphic-black", "Detail: Summer Edition graphic"],
];
const optionsJson = JSON.stringify([{ value: "", label: "None" }, ...PHOTOS.map(([value, label]) => ({ value, label }))]);
for (const f of fs.readdirSync(path.join(THEME, "sections"))) {
  const p = path.join(THEME, "sections", f);
  const s = fs.readFileSync(p, "utf8");
  if (s.includes("__PHOTOS__")) fs.writeFileSync(p, s.replaceAll("__PHOTOS__", optionsJson));
}

const cases = [];
for (const [key] of PHOTOS) {
  const e = manifest[key];
  if (!e) throw new Error(`missing photo ${key}`);
  const w = [...e.widths].reverse().find((x) => x <= 1600) ?? e.widths[0];
  const out = path.join(ASSETS, `ps-${key}.webp`);
  // Re-encode at a theme-friendly size (Shopify serves assets from its CDN as-is).
  const img = sharp(path.join(ROOT, "public/images", `${key}-${w}.webp`)).resize({ width: Math.min(w, 1400) });
  const info = await img.webp({ quality: 72 }).toFile(out);
  cases.push(
    `  {%- when '${key}' -%}\n    <img src="{{ 'ps-${key}.webp' | asset_url }}" alt="{{ alt | escape }}" width="${info.width}" height="${info.height}" loading="{{ loading | default: 'lazy' }}" decoding="async" class="{{ class }}"{% if style != blank %} style="{{ style }}"{% endif %}>`
  );
}
fs.writeFileSync(
  path.join(SNIPPETS, "bundled-photo.liquid"),
  `{%- comment -%}\n  Bundled Peak Side campaign photos (assets/ps-*.webp). Generated by scripts/build-shopify-theme.mjs.\n  Params: key, alt, class, loading, style\n{%- endcomment -%}\n{%- case key -%}\n${cases.join("\n")}\n{%- endcase -%}\n`
);

// 2. Fonts and the PKS mark.
const font = (from, to) => fs.copyFileSync(path.join(ROOT, "node_modules", from), path.join(ASSETS, to));
font("@fontsource-variable/archivo/files/archivo-latin-wdth-normal.woff2", "archivo-latin-wdth-normal.woff2");
font("@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-400-normal.woff2", "ibm-plex-mono-latin-400-normal.woff2");
font("@fontsource/ibm-plex-mono/files/ibm-plex-mono-latin-500-normal.woff2", "ibm-plex-mono-latin-500-normal.woff2");
fs.copyFileSync(path.join(ROOT, "public/images/mark-pks-480.webp"), path.join(ASSETS, "mark-pks.webp"));

// 3. JavaScript: shared interactive components + theme behaviour, down-levelled for older phones.
buildSync({ entryPoints: [path.join(ROOT, "src/interactive/index.ts")], bundle: true, format: "iife", minify: true, target: ["es2017", "safari12"], outfile: path.join(ASSETS, "interactive.js") });
const themeJs = transformSync(fs.readFileSync(path.join(SRC, "theme.js"), "utf8"), { minify: true, target: ["es2017", "safari12"] });
fs.writeFileSync(path.join(ASSETS, "theme.js"), themeJs.code);

// 4. CSS: the website's globals.css + Shopify extras, compiled by Tailwind against the Liquid files.
const globals = fs.readFileSync(path.join(ROOT, "src/app/globals.css"), "utf8").replace(/^@import .*$/gm, "");
const input = path.join(SRC, ".theme-input.css");
fs.writeFileSync(input, globals + "\n" + fs.readFileSync(path.join(SRC, "theme-extra.css"), "utf8"));
execFileSync(
  "npx",
  ["tailwindcss", "-c", "tailwind.config.ts", "-i", input, "-o", path.join(ASSETS, "theme.css"), "--minify", "--content", "./shopify-theme/**/*.liquid,./shopify-src/theme.js"],
  { stdio: "inherit", cwd: ROOT }
);
fs.rmSync(input);

// 5. Zip (theme folders at the root of the archive, as Shopify expects).
fs.mkdirSync(path.join(ROOT, "deliverables"), { recursive: true });
const zip = path.join(ROOT, "deliverables", "peak-side-shopify-theme.zip");
fs.rmSync(zip, { force: true });
execFileSync("zip", ["-qr", zip, "assets", "config", "layout", "locales", "sections", "snippets", "templates"], { cwd: THEME });

const size = (p) => `${(fs.statSync(p).size / 1024).toFixed(0)} KB`;
console.log(`theme.css ${size(path.join(ASSETS, "theme.css"))}, theme.js ${size(path.join(ASSETS, "theme.js"))}, interactive.js ${size(path.join(ASSETS, "interactive.js"))}`);
console.log(`zip: ${zip} (${size(zip)})`);
